//   脚本改了十几轮之后，散落在各个 .md 里的"搭建要求"必然和代码对不上 ——
//   用户明确提过这个问题（"因为改了很多次脚本，重新确认一下本次实验的搭建要求"）。
//   靠人去同步文档一定会漏，所以改成**从代码里抠事实**再生成：
//     · 要哪些容器    ← engine_adapter_qianxing.lua 的 MANAGED + ui_controller.lua 的 kind="container"
//     · 格子怎么算    ← entry_client_script.lua 的 cfg.cells（prefab / probe / parent / auto_scan…）
//     · 键盘绑在哪    ← cfg.key_control + key_control_fallbacks
//     · 每关要什么控件 ← tools/sim/out/layout-plan.json（由 dump_layout 生成）
//   代码一变，重跑这个脚本，文档就跟着变。
//
// 用法：node tools/gen_setup_requirements.mjs
// 输出：docs/本次搭建要求.md

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const exists = (p) => fs.existsSync(path.join(ROOT, p));

const entry = read('lua/entry_client_script.lua');
const adapter = read('lua/engine_adapter_qianxing.lua');
const ui = read('lua/ui_controller.lua');

// ── 1. 从代码里抠 cfg ──────────────────────────────────────────────────────
const numAfter = (src, key) => {
  const m = new RegExp(key + '\\s*=\\s*(-?\\d+)').exec(src);
  return m ? Number(m[1]) : null;
};
const strAfter = (src, key) => {
  const m = new RegExp(key + '\\s*=\\s*"([^"]*)"').exec(src);
  return m ? m[1] : null;
};
const cfg = {
  prefab: numAfter(entry, 'prefab'),
  probe: strAfter(entry, 'probe'),
  parent: strAfter(entry, 'parent'),
  rows: numAfter(entry, 'rows'),
  cols: numAfter(entry, 'cols'),
  autoScan: /auto_scan\s*=\s*true/.test(entry),
  trayParent: strAfter(entry, 'tray_parent'),
  keyControl: strAfter(entry, 'key_control'),
  diagnoseCell: /diagnose_cell\s*=\s*true/.test(entry),
  diagnoseGrid: !/diagnose_grid\s*=\s*false/.test(entry),
};
const fb = (/key_control_fallbacks\s*=\s*\{([^}]*)\}/.exec(entry) || [, ''])[1]
  .split(',').map((s) => s.trim().replace(/["']/g, '')).filter(Boolean);

// ── 2. 容器：适配层的 MANAGED + 控制器里的父子关系 ─────────────────────────
const managed = (/local MANAGED = \{([\s\S]*?)\}/.exec(adapter) || [, ''])[1]
  .split(',').map((s) => s.trim().replace(/["']/g, '')).filter(Boolean);

const containers = [];
for (const m of ui.matchAll(/push\(\{\s*id\s*=\s*"([^"]+)"\s*,\s*kind\s*=\s*"container"(?:[^}]*?parent\s*=\s*"([^"]+)")?/g)) {
  containers.push({ id: m[1], parent: m[2] || '（画布根）' });
}

// ── 3. 关卡与控件清单（layout-plan）────────────────────────────────────────
const planPath = 'tools/sim/out/layout-plan.json';
let plan = null;
if (exists(planPath)) plan = JSON.parse(read(planPath));

const CELL_RE = /^cell\.\d+\.\d+$/;
const groups = new Map();
let cellCount = 0, otherCount = 0;
if (plan) {
  for (const n of plan.nodes) {
    if (CELL_RE.test(n.id)) { cellCount++; continue; }
    otherCount++;
    const key = n.parent || (n.kind === 'container' ? '（顶层容器）' : '（无父级）');
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(n.id);
  }
}

const levels = plan ? plan.levels : [];

